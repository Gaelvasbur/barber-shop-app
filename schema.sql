-- Create the profiles table to store user metadata
CREATE TABLE public.profiles (
    id UUID PRIMARY KEY DEFAULT auth.uid(),
    created_at TIMESTAMPTZ DEFAULT now(),
    full_name TEXT,
    role TEXT DEFAULT 'client'
);

-- Create the barbers table to store barber details
CREATE TABLE public.barbers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT now(),
    name TEXT,
    specialty TEXT
);

-- Create the appointments table to manage bookings
CREATE TABLE public.appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT now(),
    client_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    barber_id BIGINT REFERENCES public.barbers(id) ON DELETE CASCADE,
    appointment_date DATE,
    appointment_time TIME,
    status TEXT DEFAULT 'pending'
);

